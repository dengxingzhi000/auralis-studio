/**
 * 外链策略：哪些 URL 可以交给系统浏览器。
 *
 * ## 为什么要有这一层
 *
 * `shell.openExternal` 会让**系统**按 URL 的协议启动对应程序：给它一个
 * `file://` 就是让系统打开那个文件，给它一个自定义协议就是让系统按那个
 * 协议拉起程序。渲染层的内容是用户可控的（拖进来的文件名、远端链接、
 * 未来的内容渲染），所以不能把它的请求原样转交。
 *
 * 只放行 `http` / `https`：这两个协议的系统处理程序是浏览器，而浏览器
 * 本身有完整的沙箱与协议过滤。其余一律拒绝。
 *
 * ## 与浏览器那一层的区别
 *
 * Chromium 自己也会拦下一些危险协议（实测 `file://` 的 `window.open`
 * 在到达 Electron 的窗口处理器之前就被拦了，返回 `null`）。本模块是
 * **第二道**防线：浏览器拦不住的（自定义协议、协议处理器、局域网协议）
 * 由这里挡下。两层都要有 —— 浏览器会升级、会改策略，不能只依赖它。
 */

/**
 * 这个 URL 是否可以交给系统浏览器打开。
 *
 * 判定是**协议**层面的：只认 `http:` 与 `https:`，其余（`file:`、
 * 自定义协议、`javascript:`、`data:` …）一律不行。
 */
export function isOpenableExternalUrl(url: string): boolean {
  return /^https?:\/\//i.test(url);
}
