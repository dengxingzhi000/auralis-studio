//! # auralis-visualization
//!
//! 把「原始 PCM」变成「可以直接画到画布上的点」。
//!
//! ## 为什么必须多级金字塔
//!
//! `UI_SPEC.md` §3 与 `AGENTS.md`：「避免发送每个 PCM 样本给 UI」。
//!
//! 一个 3 小时的 48 kHz 立体声文件是 **1.037 亿帧**。若按画布像素（2000 px）
//! 直接抽样，需要每 5 万个采样点才取一个——**局部细节会完全丢失**：
//! 波形中间一个 10 ms 的瞬态根本不会被画到。
//!
//! 金字塔的做法是同时保留多个分辨率：
//!
//! ```text
//! level 0: 每格 256 样本   -> 200k 格   (看整体概览)
//! level 1: 每格 512 样本   -> 100k 格
//! level 2: 每格 1024 样本  -> 50k 格    (看概览 + 更多细节)
//! ...
//! level n: 每格 256·2ⁿ     -> 顶层格子数 < 视口宽度时停止
//! ```
//!
//! 画视口时**选一个够细的层级**，只取覆盖视口的那几十到几千格。
//! 于是无论文件是 3 秒还是 3 小时，传给前端的数据量都只与**画布宽度**有关，
//! 与文件长度无关。
//!
//! 内存占用同理：`sum(格数) ≈ 2 × 顶层格数`，约为原始 PCM 的 1/1000 量级。

